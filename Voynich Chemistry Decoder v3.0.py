# РАЗДЕЛ 4: АНАЛИЗАТОР (С учётом правила частотности)
# ==============================================================================
class VoynichAnalyzer:
    def __init__(self):
        self.word_freq_cache = {} # В реальном использовании здесь будет загрузка из ZL3b-n.txt

    def set_frequencies(self, freq_dict: Dict[str, int]):
        self.word_freq_cache = freq_dict

    def analyze_word(self, word: str) -> Dict:
        word = word.lower().strip()
        freq = self.word_freq_cache.get(word, 1)
        
        # ПРАВИЛО ЧАСТОТНОСТИ: Если слово встречается реже 5 раз, мы не ломаем его на морфемы.
        if freq < 5:
            return {
                "word": word,
                "type": "unique_entity",
                "meaning": "Уникальная сущность (название растения, редкий реагент или инструмент)",
                "warning": "Морфологический разбор запрещён правилом частотности во избежание подгонки."
            }

        # Для частых слов применяем матрицу (упрощённый жадный алгоритм для демонстрации)
        result = {"word": word, "type": "process", "parts": []}
        remaining = word
        
        # 1. Префикс
        for pfx, data in MORPHOLOGY_MATRIX["prefixes"].items():
            if remaining.startswith(pfx) and len(remaining) > len(pfx) + 1:
                result["parts"].append(f"PRE[{pfx}: {data['meaning']}]")
                remaining = remaining[len(pfx):]
                break
                
        # 2. Галлоус
        for glw, data in MORPHOLOGY_MATRIX["gallows"].items():
            if remaining.startswith(glw) and len(remaining) > len(glw) + 1:
                result["parts"].append(f"CAT[{glw}: {data['meaning']}]")
                remaining = remaining[len(glw):]
                break
                
        # 3. Суффикс
        for sfx, data in MORPHOLOGY_MATRIX["suffixes"].items():
            if remaining.endswith(sfx) and len(remaining) > len(sfx) + 1:
                result["parts"].append(f"SUF[{sfx}: {data['meaning']}]")
                remaining = remaining[:-len(sfx)]
                break
                
        # 4. Корень
        for root, data in MORPHOLOGY_MATRIX["roots"].items():
            if root in remaining:
                result["parts"].append(f"ROOT[{root}: {data['meaning']}]")
                remaining = remaining.replace(root, "", 1)
                break
                
        if not result["parts"]:
            result["parts"].append("UNKNOWN_ROOT")
            
        result["meaning"] = " + ".join(result["parts"])
        return result

